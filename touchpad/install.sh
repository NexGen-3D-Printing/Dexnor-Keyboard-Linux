#!/usr/bin/env bash
#
# touchpad/install.sh
#
# Fix the physical touchpad click on the Dexnor Bluetooth keyboard/touchpad
# combo under Linux.
#
# The problem
# -----------
# The touchpad reports its physical button as bit 0 of the last byte of HID
# report 6 (Digitizer / TouchPad). The kernel maps that bit to BTN_LEFT.
# The firmware sets the bit when the button is pressed, but never clears it
# when the button is released: the bit stays 1 until the first report of the
# *next* touch. Most toolkits act on button release, so a physical click does
# not complete until the user touches or moves again.
#
# What this installs
# ------------------
#   1. /usr/local/sbin/dexnor-touchpad-click.py
#      A small daemon that grabs the touchpad, forwards every event to a
#      uinput clone, and synthesises the missing BTN_LEFT release when the
#      last contact ends.
#   2. dexnor-touchpad-click.service
#      Runs the daemon at boot and restarts it when the touchpad reconnects.
#
# Tap-to-click is untouched: libinput generates it from touch events and
# never uses BTN_LEFT.
#
# Usage
# -----
#   ./touchpad/install.sh              # install / repair
#   ./touchpad/install.sh --uninstall  # remove everything
#
# Optional environment overrides:
#   TOUCHPAD_NAME   evdev device name (default "Dexnor Keyboard Touchpad")
#   DISABLE_BLUETOOTH_PM  set to 1 to skip Bluetooth power management changes

set -euo pipefail

# ------------------------------------------------------------ sudo check
# Prompt for sudo password at the start if not running as root
if [[ ${EUID} -ne 0 ]]; then
    echo "This script requires root privileges."
    if command -v sudo >/dev/null 2>&1; then
        # Try to get sudo credentials upfront
        echo "Prompting for sudo password..."
        if ! sudo -v; then
            echo "Failed to get sudo privileges. Exiting." >&2
            exit 1
        fi
        # Run the script again with sudo
        exec sudo "$0" "$@"
    else
        echo "sudo not found. Please run this script as root." >&2
        exit 1
    fi
fi

PY=/usr/local/sbin/dexnor-touchpad-click.py
UNIT=/etc/systemd/system/dexnor-touchpad-click.service
SERVICE=dexnor-touchpad-click.service
TOUCHPAD_NAME=${TOUCHPAD_NAME:-Dexnor Keyboard Touchpad}
DISABLE_BLUETOOTH_PM=${DISABLE_BLUETOOTH_PM:-0}

# ---------------------------------------------------------------- uninstall
if [[ ${1:-} == "--uninstall" ]]; then
    systemctl disable --now "$SERVICE" 2>/dev/null || true
    rm -f "$UNIT" "$PY"
    systemctl daemon-reload
    echo "Removed $SERVICE and $PY."
    exit 0
fi

# ------------------------------------------------------------ dependencies
if ! python3 -c 'import evdev' >/dev/null 2>&1; then
    echo "python3-evdev is required for the touchpad fix." >&2
    echo "On Fedora: sudo dnf install python3-evdev" >&2
    exit 1
fi
if [[ ! -e /dev/uinput ]]; then
    echo "/dev/uinput not found. Load the uinput module or enable it in the kernel." >&2
    exit 1
fi

# -------------------------------------------------- disable Bluetooth power management
if [[ "$DISABLE_BLUETOOTH_PM" == "0" ]]; then
    echo "Bluetooth power management optimization:"
    if [[ -w /sys/class/bluetooth/hci0/power/control ]]; then
        echo "on" > /sys/class/bluetooth/hci0/power/control
        echo "  [OK] Runtime power management disabled (improves connection stability)"
    else
        echo "  [INFO] Power management control not available"
    fi
else
    echo "Bluetooth power management optimization: SKIPPED"
fi
echo

# --------------------------------------------------------------- write daemon
cat > "$PY" <<'PYEOF'
#!/usr/bin/env python3
"""Fix the Dexnor touchpad's stuck left-button release.

The Dexnor keyboard/touchpad combo reports the physical touchpad button as
bit 0 of the last byte of HID report 6 (Digitizer/TouchPad), which the kernel
maps to BTN_LEFT.  The firmware sets that bit when the button is pressed but
never clears it when the button is released: the bit stays 1 until the first
report of the *next* touch.  Most toolkits act on button release, so a
physical click does not complete until the user touches or moves again.

This daemon grabs the touchpad, forwards every event unchanged to a uinput
clone, and synthesises the missing BTN_LEFT release when the last contact
ends.  Tap-to-click is untouched: it is generated by libinput from touch
events and never uses BTN_LEFT.
"""

import os
import select
import signal
import sys
import time

import evdev
from evdev import ecodes

DEVICE_NAME = os.environ.get("TOUCHPAD_NAME", "Dexnor Keyboard Touchpad")


def log(msg):
    print(msg, flush=True)


def is_physical(dev):
    """True only for the real Bluetooth HID device, not a uinput clone."""
    node = os.path.basename(dev.path)          # event23
    syspath = os.path.realpath("/sys/class/input/%s/device" % node)
    return "/uhid/" in syspath


def find_device():
    for path in evdev.list_devices():
        try:
            dev = evdev.InputDevice(path)
        except (PermissionError, OSError):
            continue
        if dev.name == DEVICE_NAME and is_physical(dev):
            return dev
        dev.close()
    return None


def make_uinput(dev):
    caps = dev.capabilities()
    caps.pop(ecodes.EV_SYN, None)
    caps.pop(ecodes.EV_FF, None)
    return evdev.UInput(
        events=caps,
        name=dev.name,
        vendor=dev.info.vendor,
        product=dev.info.product,
        version=dev.info.version,
        bustype=dev.info.bustype,
        phys=dev.phys,
        input_props=dev.input_props(),
    )


def run(dev, verbose):
    ui = None
    try:
        ui = make_uinput(dev)
        log("virtual device: %s" % ui.device.path)
        dev.grab()
        log("grabbed %s (%s)" % (dev.path, dev.name))

        btn_out = 0          # BTN_LEFT state as seen by consumers
        touching = False
        active_slots = set()
        cur_slot = 0

        if ecodes.BTN_LEFT in dev.active_keys():
            log("note: BTN_LEFT was already latched at startup; ignoring it")

        while True:
            r, _, _ = select.select([dev.fd], [], [], 0.5)
            if not r:
                continue
            try:
                events = list(dev.read())
            except BlockingIOError:
                continue

            for ev in events:
                if ev.type == ecodes.EV_KEY and ev.code == ecodes.BTN_LEFT:
                    if verbose:
                        log("kernel BTN_LEFT=%d (out=%d)" % (ev.value, btn_out))
                    if ev.value != btn_out:
                        ui.write_event(ev)
                        btn_out = ev.value
                    continue

                if ev.type == ecodes.EV_KEY and ev.code == ecodes.BTN_TOUCH:
                    touching = bool(ev.value)
                    ui.write_event(ev)
                    if not touching and btn_out:
                        ui.write(ecodes.EV_KEY, ecodes.BTN_LEFT, 0)
                        btn_out = 0
                        if verbose:
                            log("synthesised BTN_LEFT=0 at contact end")
                    continue

                if ev.type == ecodes.EV_ABS:
                    if ev.code == ecodes.ABS_MT_SLOT:
                        cur_slot = ev.value
                    elif ev.code == ecodes.ABS_MT_TRACKING_ID:
                        if ev.value == -1:
                            active_slots.discard(cur_slot)
                        else:
                            active_slots.add(cur_slot)
                    ui.write_event(ev)
                    continue

                ui.write_event(ev)

                # Safety net: if BTN_TOUCH was not emitted but every contact
                # is gone, release the button on the SYN_REPORT that closes
                # the frame.
                if (ev.type == ecodes.EV_SYN and ev.code == ecodes.SYN_REPORT
                        and not active_slots and not touching and btn_out):
                    ui.write(ecodes.EV_KEY, ecodes.BTN_LEFT, 0)
                    btn_out = 0
                    if verbose:
                        log("synthesised BTN_LEFT=0 at last contact")

    finally:
        try:
            dev.ungrab()
        except Exception:
            pass
        if ui is not None:
            ui.close()
        dev.close()


def main():
    verbose = "--verbose" in sys.argv[1:]

    if os.geteuid() != 0:
        print("run as root", file=sys.stderr)
        return 1

    def stop(_signum, _frame):
        raise SystemExit(0)

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)

    while True:
        dev = find_device()
        if dev is None:
            time.sleep(1)
            continue
        try:
            run(dev, verbose)
        except SystemExit:
            return 0
        except Exception as exc:
            log("error: %s" % exc)
        time.sleep(1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
PYEOF

chmod 0755 "$PY"

# ------------------------------------------------------------- write service
cat > "$UNIT" <<EOF
[Unit]
Description=Fix Dexnor touchpad stuck left-button release
After=bluetooth.service
Wants=bluetooth.service

[Service]
Type=simple
ExecStart=$PY
Restart=always
RestartSec=2
Environment="TOUCHPAD_NAME=$TOUCHPAD_NAME"

[Install]
WantedBy=multi-user.target
EOF

# ------------------------------------------------------------------- activate
systemctl daemon-reload
systemctl enable "$SERVICE" >/dev/null || true
systemctl restart "$SERVICE" || true

sleep 1
echo "== service =="
systemctl is-enabled "$SERVICE" || true
systemctl is-active "$SERVICE" || true
echo
echo "== logs ="
journalctl -u "$SERVICE" -n 12 --no-pager || true
echo
echo "== touchpad devices ="
for e in /sys/class/input/event*; do
    n=$(cat "$e/device/name" 2>/dev/null)
    [[ $n == "$TOUCHPAD_NAME" ]] && echo "  $(basename "$e") -> $n"
done
echo
echo "Done. Check status any time with:"
echo "  sudo journalctl -u $SERVICE -f"
echo "  sudo $PY --verbose   # run in the foreground for debugging"
